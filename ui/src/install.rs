//! First start: Cardul ships without anything from the original game, so it asks for the
//! player's own copy of Autoduel (DOS) and builds its classic graphics and world data from it
//! ([`cardul_import`]). This screen needs no game files: it draws with a built-in font.
use crate::fb::{col, Frame};
use crate::input::{Input, Key};
use std::path::{Path, PathBuf};

/// What the player did on the setup screen.
pub enum Outcome {
    /// the game's files were imported; start the game
    Imported(cardul_import::Summary),
    Quit,
}

pub struct Installer {
    /// where the import goes
    assets: PathBuf,
    /// folders searched for the game, the first one is where the player is asked to put it
    places: Vec<PathBuf>,
    /// why the last look failed
    problem: Option<String>,
    frame: Frame,
    tick: u64,
}

/// Look for the game in `places` and import the first copy found into `assets`. Err: the
/// most useful reason none could be used.
pub fn import_from(places: &[PathBuf], assets: &Path) -> Result<cardul_import::Summary, String> {
    let mut problem = None;
    for p in places {
        match cardul_import::Original::open(p) {
            Ok(o) => return cardul_import::import(&o, assets).map_err(|e| format!("The import failed: {}", e)),
            // a folder with some of the files says more than an empty one
            Err(e @ (cardul_import::Problem::Missing { .. } | cardul_import::Problem::Bad(_))) => problem = Some(e.to_string()),
            Err(e) => {
                if problem.is_none() {
                    problem = Some(e.to_string());
                }
            }
        }
    }
    Err(problem.unwrap_or_else(|| "No Autoduel (DOS) files were found.".into()))
}

impl Installer {
    pub fn new(assets: PathBuf, places: Vec<PathBuf>, problem: Option<String>) -> Installer {
        if let Some(p) = places.first() {
            let _ = std::fs::create_dir_all(p);
        }
        Installer { assets, places, problem, frame: Frame::new(1), tick: 0 }
    }
    pub fn tick_count(&self) -> u64 {
        self.tick
    }

    /// Look again (Enter), or in a folder dropped on the window.
    pub fn retry(&mut self, dropped: Option<&Path>) -> Option<Outcome> {
        let mut places = vec![];
        if let Some(d) = dropped {
            places.push(if d.is_file() { d.parent().unwrap_or(d).to_path_buf() } else { d.to_path_buf() });
        }
        places.extend(self.places.iter().cloned());
        match import_from(&places, &self.assets) {
            Ok(s) => Some(Outcome::Imported(s)),
            Err(e) => {
                self.problem = Some(e);
                None
            }
        }
    }

    pub fn tick(&mut self, inp: &Input) -> Option<Outcome> {
        self.tick += 1;
        for k in &inp.keys {
            match k {
                Key::Esc => return Some(Outcome::Quit),
                Key::Enter | Key::Space => return self.retry(None),
                _ => {}
            }
        }
        None
    }

    pub fn draw(&mut self) -> &Frame {
        // (text, colour); None = a blank line
        let mut lines: Vec<Option<(String, u32)>> = vec![Some(("         CARDUL - first start".into(), col::WHITE)), None];
        let para = |lines: &mut Vec<Option<(String, u32)>>, s: &str, c: u32| {
            lines.extend(wrap(s, 37).into_iter().map(|l| Some((l, c))));
        };
        para(&mut lines, "Cardul comes without the original game's graphics, maps and text. It makes them from your own copy of Autoduel for DOS.", col::LIGHT_GREY);
        lines.push(None);
        para(&mut lines, "Copy all the files of your Autoduel (DOS) into this folder:", col::WHITE);
        let dir = self.places.first().map(|p| std::path::absolute(p).unwrap_or(p.clone()).display().to_string()).unwrap_or_default();
        lines.extend(wrap_path(&dir, 35).into_iter().map(|l| Some((format!("  {}", l), col::YELLOW))));
        lines.push(None);
        para(&mut lines, "or drag the Autoduel folder onto this window.", col::WHITE);
        if let Some(p) = &self.problem {
            lines.push(None);
            para(&mut lines, p, col::LIGHT_RED);
        }
        let f = &mut self.frame;
        f.clear(col::BLACK);
        f.rect(2, 2, 316, 196, 2, col::LIGHT_GREY);
        for (row, l) in lines.iter().take(21).enumerate() {
            if let Some((s, c)) = l {
                text(f, 8, 8 * (row as i32 + 1), s, *c);
            }
        }
        let blink = (self.tick / 30).is_multiple_of(2);
        text(f, 8, 8 * 23, "Enter: look again", if blink { col::WHITE } else { col::LIGHT_GREY });
        text(f, 8 + 8 * 28, 8 * 23, "Esc: quit", col::LIGHT_GREY);
        &self.frame
    }
}

/// Word-wrap to `w` columns.
fn wrap(s: &str, w: usize) -> Vec<String> {
    let mut out = vec![];
    let mut cur = String::new();
    for word in s.split_whitespace() {
        if !cur.is_empty() && cur.len() + 1 + word.len() > w {
            out.push(std::mem::take(&mut cur));
        }
        if !cur.is_empty() {
            cur.push(' ');
        }
        cur.push_str(word);
        while cur.len() > w {
            let rest = cur.split_off(w);
            out.push(std::mem::replace(&mut cur, rest));
        }
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// A path split into lines of `w` characters, at separators where it can.
fn wrap_path(p: &str, w: usize) -> Vec<String> {
    let mut out = vec![];
    let mut rest = p.to_string();
    while rest.chars().count() > w {
        let head: String = rest.chars().take(w).collect();
        let cut = head.rfind(['/', '\\']).filter(|&i| i > w / 2).map(|i| i + 1).unwrap_or(head.len());
        out.push(rest[..cut].to_string());
        rest = rest[cut..].to_string();
    }
    out.push(rest);
    out
}

/// Text in the built-in font at (x, y).
fn text(f: &mut Frame, x: i32, y: i32, s: &str, c: u32) {
    for (i, ch) in s.chars().enumerate() {
        let code = ch as u32;
        let g = if (0x20..0x7F).contains(&code) { FONT[(code - 0x20) as usize] } else { FONT[('?' as u32 - 0x20) as usize] };
        for (r, bits) in g.iter().enumerate() {
            for b in 0..8 {
                if bits >> b & 1 != 0 {
                    f.pixel(x + 8 * i as i32 + b, y + r as i32, c);
                }
            }
        }
    }
}

